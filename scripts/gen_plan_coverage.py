#!/usr/bin/env python3
"""Generate docs/guides/plan-coverage.md from drt.engine.plan_coverage (#1223).

Usage:
    python scripts/gen_plan_coverage.py           # rewrite the doc
    python scripts/gen_plan_coverage.py --check   # exit 1 if the doc is stale
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import drt.connectors  # noqa: F401 — registers the built-in destinations
from drt.engine.plan_coverage import PLAN_COVERAGE, PLAN_STATUSES

DOC = Path(__file__).resolve().parent.parent / "docs" / "guides" / "plan-coverage.md"

_HEADINGS = {
    "available": "Planned (true create / update / delete change set)",
    "partial": "Partly planned",
    "needs-api-diff": "Not planned yet — could be (API-based diff, #472)",
    "unavailable": "Not planned — no target state to diff",
}


def render() -> str:
    lines = [
        "# `drt plan` coverage by destination",
        "",
        "<!-- Generated by scripts/gen_plan_coverage.py from drt/engine/plan_coverage.py. "
        "Do not edit by hand. -->",
        "",
        "`drt plan` / `drt apply` need to know what a destination currently holds. Where "
        "that is not possible, `drt plan` exits 1 with a reason and writes no file "
        "([When a plan is unavailable](plan.md#when-a-plan-is-unavailable)). This page is "
        "generated from the per-destination declaration in `drt/engine/plan_coverage.py`; "
        "a test keeps each declaration in line with the code, and CI fails when a built-in "
        "destination has none.",
        "",
    ]
    for status in PLAN_STATUSES:
        members = sorted(name for name, c in PLAN_COVERAGE.items() if c.status == status)
        lines += [f"## {_HEADINGS[status]}", ""]
        if not members:
            lines += ["_None._", ""]
            continue
        if status == "available":
            lines += [", ".join(f"`{m}`" for m in members), ""]
            continue
        lines += ["| Destination | Why |", "|---|---|"]
        lines += [f"| `{m}` | {PLAN_COVERAGE[m].reason} |" for m in members]
        lines.append("")
    lines += [
        "Every plan also needs `destination.upsert_key` and a sync a plan can represent; see "
        "[When a plan is unavailable](plan.md#when-a-plan-is-unavailable). A third-party "
        "(plugin) destination needs no entry and is not listed here; whether it can be planned "
        "depends on what it implements.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not DOC.exists() or DOC.read_text() != text:
            print(f"{DOC} is stale; run: python scripts/gen_plan_coverage.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text)
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
